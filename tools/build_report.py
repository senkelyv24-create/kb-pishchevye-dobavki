def setup(doc):
    section = doc.sections[0]
    section.page_width = Mm(210)
    section.page_height = Mm(297)
    section.left_margin = Mm(30)
    section.right_margin = Mm(15)
    section.top_margin = Mm(20)
    section.bottom_margin = Mm(20)
    section.different_first_page_header_footer = True
    section.orientation = WD_ORIENT.PORTRAIT
    normal = doc.styles["Normal"]
    shade_style(normal)
    pf = normal.paragraph_format
    pf.line_spacing_rule = WD_LINE_SPACING.ONE_POINT_FIVE
    pf.space_after = Pt(0)
    pf.space_before = Pt(0)
    pf.first_line_indent = Cm(1.25)
    add_page_field(section.footer.paragraphs[0])
    section.footer.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
    section.first_page_footer.paragraphs[0].text = ""


def add_page_field(paragraph):
    paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = paragraph.add_run()
    set_run_font(run, 12)
    begin = OxmlElement("w:fldChar")
    begin.set(qn("w:fldCharType"), "begin")
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = " PAGE "
    end = OxmlElement("w:fldChar")
    end.set(qn("w:fldCharType"), "end")
    run._r.append(begin)
    run._r.append(instr)
    run._r.append(end)


def para(doc, text, *, center=False, bold=False, italic=False, indent=True, size=14, space_before=0, space_after=0):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER if center else WD_ALIGN_PARAGRAPH.JUSTIFY
    p.paragraph_format.line_spacing = 1.5
    p.paragraph_format.space_before = Pt(space_before)
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.first_line_indent = Cm(0 if center or not indent else 1.25)
    run = p.add_run(text)
    set_run_font(run, size, bold, italic)
    return p


def chapter(doc, text):
    doc.add_page_break()
    para(doc, text, center=True, bold=True, indent=False, space_after=12)


def section_title(doc, text):
    para(doc, text, bold=True, indent=False, space_before=12, space_after=6)


def bullets(doc, items):
    for item in items:
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        p.paragraph_format.line_spacing = 1.5
        p.paragraph_format.left_indent = Cm(1.25)
        p.paragraph_format.first_line_indent = Cm(0)
        run = p.add_run("– " + item)
        set_run_font(run, 14)


def figure(doc, filename, caption):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.first_line_indent = Cm(0)
    p.paragraph_format.space_before = Pt(8)
    run = p.add_run()
    set_run_font(run)
    run.add_picture(str(IMG / filename), width=Cm(15.5))
    para(doc, caption, center=True, bold=True, indent=False)
    para(doc, "Примечание — Источник: собственная разработка.", center=True, italic=True, indent=False, space_after=6)


def add_table(doc, headers, rows):
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.style = "Table Grid"
    for i, header in enumerate(headers):
        cell = table.rows[0].cells[i]
        cell.text = ""
        p = cell.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.first_line_indent = Cm(0)
        run = p.add_run(header)
        set_run_font(run, 12, bold=True)
    for r, row in enumerate(rows, start=1):
        for c, value in enumerate(row):
            cell = table.rows[r].cells[c]
            cell.text = ""
            p = cell.paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.LEFT
            p.paragraph_format.first_line_indent = Cm(0)
            run = p.add_run(value)
            set_run_font(run, 12)
    para(doc, "", indent=False)


def title_line(doc, text="", *, bold=False, center=True):
    """Строка титульного листа: одинарный интервал, как в шаблоне кафедры."""
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER if center else WD_ALIGN_PARAGRAPH.LEFT
    p.paragraph_format.line_spacing = 1.0
    p.paragraph_format.space_before = Pt(0)
    p.paragraph_format.space_after = Pt(0)
    p.paragraph_format.first_line_indent = Cm(0)
    run = p.add_run(text)
    set_run_font(run, 14, bold)
    return p


def supervisor_block(doc):
    """Правая колонка без рамок — так руководитель стоит в образце титульного листа."""
    table = doc.add_table(rows=1, cols=2)
    table.autofit = False
    table.allow_autofit = False
    tbl = table._tbl
    tbl_pr = tbl.tblPr
    borders = OxmlElement("w:tblBorders")
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        element = OxmlElement(f"w:{edge}")
        element.set(qn("w:val"), "nil")
        element.set(qn("w:sz"), "0")
        element.set(qn("w:space"), "0")
        element.set(qn("w:color"), "auto")
        borders.append(element)
    tbl_pr.append(borders)
    widths = (Cm(8.2), Cm(8.2))
    for cell, width in zip(table.rows[0].cells, widths):
        cell.width = width
    lines = [
        "Научный руководитель",
        "Зайкова Светлана Алексеевна,",
        "доцент кафедры",
        "системного программирования и компьютерной безопасности,",
        "кандидат физ.-мат. наук, доцент",
    ]
    cell = table.rows[0].cells[1]
    for index, line in enumerate(lines):
        paragraph = cell.paragraphs[0] if index == 0 else cell.add_paragraph()
        paragraph.alignment = WD_ALIGN_PARAGRAPH.RIGHT
        paragraph.paragraph_format.line_spacing = 1.0
        paragraph.paragraph_format.space_before = Pt(0)
        paragraph.paragraph_format.space_after = Pt(0)
        paragraph.paragraph_format.first_line_indent = Cm(0)
        run = paragraph.add_run(line)
        set_run_font(run, 14)
    left = table.rows[0].cells[0].paragraphs[0]
    left.paragraph_format.first_line_indent = Cm(0)
    left.paragraph_format.line_spacing = 1.0


